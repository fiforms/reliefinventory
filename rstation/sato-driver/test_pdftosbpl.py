import importlib.machinery
import importlib.util
import re
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

HERE = Path(__file__).parent
FILTER = HERE / "pdftosbpl"

loader = importlib.machinery.SourceFileLoader("pdftosbpl", str(FILTER))
spec = importlib.util.spec_from_loader("pdftosbpl", loader)
filt = importlib.util.module_from_spec(spec)
loader.exec_module(filt)

needs_gs = pytest.mark.skipif(shutil.which("gs") is None, reason="Ghostscript not installed")


def make_pdf(path, pages, width_pt=166, height_pt=288):
    """A PDF whose pages each have a black bar at the bottom, via Ghostscript."""
    ps = path.with_suffix(".ps")
    body = "".join(
        f"<</PageSize [{width_pt} {height_pt}]>> setpagedevice 0 setgray 0 0 {width_pt} 40 rectfill showpage\n"
        for _ in range(pages))
    ps.write_text("%!PS\n" + body)
    subprocess.run(["gs", "-q", "-dNOPAUSE", "-dBATCH", "-sDEVICE=pdfwrite", f"-sOutputFile={path}", str(ps)], check=True)
    return path


def run_filter(args, stdin=None):
    return subprocess.run([sys.executable, "-I", str(FILTER), *args], input=stdin, capture_output=True)


def test_parse_options_and_shift():
    options = filt.parse_options("PageSize=w166h288 Resolution=305dpi RIHShift=Right10 print-scaling=none")
    assert filt.dpi_from(options) == 305
    assert filt.shift_from(options) == 10
    assert filt.shift_from({"RIHShift": "Left20"}) == -20
    assert filt.shift_from({"RIHShift": "Zero"}) == 0
    assert filt.shift_from({}) == filt.DEFAULT_SHIFT
    assert filt.shift_from({"RIHShift": "bogus"}) == filt.DEFAULT_SHIFT


def test_default_shift_matches_the_ppd():
    ppd = (HERE / "sato-sbpl.ppd").read_text()
    assert re.search(r"^\*DefaultRIHShift: Left5$", ppd, re.M) and filt.DEFAULT_SHIFT == -5
    assert "*cupsFilter: \"application/pdf 0 pdftosbpl\"" in ppd


def test_pbm_reader_skips_comments_and_reads_several_pages():
    page = b"P4\n# Image generated by Ghostscript\n10 2\n" + bytes([0xFF, 0xC0, 0x00, 0x00])
    pages = list(filt.read_pbm_pages(page + page))
    assert [(w, h) for w, h, _ in pages] == [(10, 2), (10, 2)]
    assert pages[0][2] == bytes([0xFF, 0xC0, 0x00, 0x00])


def test_label_job_layout_pads_to_strips_skips_blank_ones_and_crops_left():
    # 16 x 10 dots; only row 9 (second strip) has ink, in the leftmost 8 dots
    rows = bytearray(2 * 10)
    rows[9 * 2] = 0xFF
    job = filt.label_job(16, 10, bytes(rows), shift=-4, copies=3)
    assert job.startswith(b"\x1bA\x1bA1" + b"0016" + b"0016" + b"\x1bA3V0000H0000")  # length padded 10 -> 16
    assert job.endswith(b"\x1bQ3\x1bZ")
    assert job.count(b"\x1bGB") == 1  # the blank first strip is skipped
    strip = job.split(b"\x1bGB002001")[1].split(b"\x1bQ")[0]
    assert len(strip) == 16 and strip[2:4] == bytes([0xF0, 0x00])  # row 1 of the strip: ink shifted 4 dots left
    assert b"\x1bH0\x1bV0008" in job


def test_label_job_right_shift_and_size_limit():
    assert b"\x1bH12\x1bV0000" in filt.label_job(8, 8, b"\xff" * 8, shift=12, copies=1)
    with pytest.raises(ValueError):
        filt.label_job(8, 10000, b"\x00" * 10000, shift=0, copies=1)


@needs_gs
def test_one_job_per_pdf_page_with_copies_and_page_accounting(tmp_path):
    pdf = make_pdf(tmp_path / "labels.pdf", pages=3)
    result = run_filter(["7", "daniel", "labels", "2", "Resolution=203dpi"], pdf.read_bytes())
    assert result.returncode == 0, result.stderr
    assert len(re.findall(rb"\x1bA1\d{8}", result.stdout)) == 3
    assert result.stdout.count(b"\x1bQ2\x1bZ") == 3
    assert re.findall(r"PAGE: (\d+) (\d+)", result.stderr.decode()) == [("1", "2"), ("2", "2"), ("3", "2")]
    assert b"\x1bA10816" + b"0468" in result.stdout  # 4 in = 288 pt -> 812 dots; width 166 pt -> 468 dots


@needs_gs
def test_file_argument_and_size_follow_the_page_and_dpi(tmp_path):
    pdf = make_pdf(tmp_path / "one.pdf", pages=1, width_pt=288, height_pt=468)  # 4 x 6.5 in
    result = run_filter(["1", "u", "t", "1", "Resolution=305dpi", str(pdf)])
    assert result.returncode == 0, result.stderr
    assert b"\x1bA1" + b"1984" + b"1220" in result.stdout  # 6.5 in -> 1982 dots padded to 1984; 4 in -> 1220


@needs_gs
def test_bad_pdf_is_a_cups_error_not_a_crash(tmp_path):
    result = run_filter(["1", "u", "t", "1", ""], b"this is not a pdf")
    assert result.returncode == 1
    assert result.stderr.decode().startswith("ERROR: ")
