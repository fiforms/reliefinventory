//! Persistent identity: `server_url`, a `device_uuid` generated once and kept forever (the server
//! recognises the same machine across re-pairing by it), and this machine's Ed25519 key.
//!
//! The private key seed is generated on first run and survives un-pairing (un-pairing only forgets the
//! server's side of the trust). It lives in `config.json` inside the per-user app-data directory, written
//! 0600 on Unix (Windows app-data is per-user ACL'd). It is never logged: `Config` has a hand-written `Debug`.

use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

#[derive(Serialize, Deserialize, Clone, Default)]
pub struct Config {
    #[serde(default)]
    pub server_url: Option<String>,
    pub device_uuid: String,
    #[serde(default)]
    pub device_name: Option<String>,
    /// Base64url 32-byte Ed25519 seed. Generated by `load_or_create`; never leaves this file.
    #[serde(default)]
    pub private_key: Option<String>,
    /// The server's public key as returned when pairing (shown so it can be compared; the server never sends a secret).
    #[serde(default)]
    pub server_public_key: Option<String>,
    #[serde(default)]
    pub paired: bool,
}

impl std::fmt::Debug for Config {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Config")
            .field("server_url", &self.server_url)
            .field("device_uuid", &self.device_uuid)
            .field("device_name", &self.device_name)
            .field("private_key", &self.private_key.as_ref().map(|_| "<redacted>"))
            .field("server_public_key", &self.server_public_key)
            .field("paired", &self.paired)
            .finish()
    }
}

impl Config {
    pub fn path(dir: &Path) -> PathBuf {
        dir.join("config.json")
    }

    /// Load, or create with a fresh `device_uuid` on first run.
    pub fn load_or_create(dir: &Path) -> std::io::Result<Config> {
        std::fs::create_dir_all(dir)?;
        let p = Self::path(dir);
        if let Ok(text) = std::fs::read_to_string(&p) {
            if let Ok(mut c) = serde_json::from_str::<Config>(&text) {
                // A config from before keys existed (it held a bearer token, now ignored) gets a key and
                // must be paired again.
                if c.private_key.is_none() {
                    c.private_key = Some(crate::identity::generate_seed());
                    c.paired = false;
                    c.save(dir)?;
                }
                return Ok(c);
            }
            // Unreadable config: keep it for inspection but never reuse a half-written identity.
            let _ = std::fs::rename(&p, dir.join("config.json.corrupt"));
        }
        let c = Config {
            device_uuid: uuid::Uuid::new_v4().to_string(),
            private_key: Some(crate::identity::generate_seed()),
            ..Default::default()
        };
        c.save(dir)?;
        Ok(c)
    }

    pub fn save(&self, dir: &Path) -> std::io::Result<()> {
        write_private(&Self::path(dir), serde_json::to_vec_pretty(self)?.as_slice())
    }

    pub fn is_paired(&self) -> bool {
        self.paired && self.private_key.is_some() && self.server_url.is_some()
    }

    /// This machine's signing identity.
    pub fn identity(&self) -> Option<crate::identity::Identity> {
        self.private_key.as_deref().and_then(crate::identity::Identity::from_seed)
    }
}

/// Atomic write (tmp + rename), owner-only on Unix.
pub fn write_private(path: &Path, bytes: &[u8]) -> std::io::Result<()> {
    use std::io::Write;
    let tmp = path.with_extension("tmp");
    {
        let mut opts = std::fs::OpenOptions::new();
        opts.write(true).create(true).truncate(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt;
            opts.mode(0o600);
        }
        let mut f = opts.open(&tmp)?;
        f.write_all(bytes)?;
        f.sync_all()?;
    }
    std::fs::rename(&tmp, path)
}

/// Default per-user data directory for the app.
pub fn default_data_dir() -> PathBuf {
    dirs::data_dir().unwrap_or_else(|| PathBuf::from(".")).join("RI Print")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn uuid_and_key_are_stable_and_key_redacted() {
        let d = tempfile::tempdir().unwrap();
        let a = Config::load_or_create(d.path()).unwrap();
        let b = Config::load_or_create(d.path()).unwrap();
        assert_eq!(a.device_uuid, b.device_uuid);
        assert_eq!(a.private_key, b.private_key);
        assert!(a.identity().is_some());
        let seed = b.private_key.clone().unwrap();
        assert!(!format!("{b:?}").contains(&seed));
        b.save(d.path()).unwrap();
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mode = std::fs::metadata(Config::path(d.path())).unwrap().permissions().mode();
            assert_eq!(mode & 0o077, 0, "config must not be group/world readable");
        }
    }

    #[test]
    fn an_old_config_with_a_token_gets_a_key_and_is_unpaired() {
        let d = tempfile::tempdir().unwrap();
        std::fs::write(
            Config::path(d.path()),
            r#"{"server_url":"https://x.example","device_uuid":"u-1","token":"old"}"#,
        )
        .unwrap();
        let c = Config::load_or_create(d.path()).unwrap();
        assert_eq!(c.device_uuid, "u-1");
        assert!(c.private_key.is_some());
        assert!(!c.is_paired());
        assert!(!std::fs::read_to_string(Config::path(d.path())).unwrap().contains("old"));
    }

    #[test]
    fn corrupt_config_gets_a_new_identity_but_is_kept() {
        let d = tempfile::tempdir().unwrap();
        std::fs::write(Config::path(d.path()), "{not json").unwrap();
        let c = Config::load_or_create(d.path()).unwrap();
        assert!(!c.device_uuid.is_empty());
        assert!(d.path().join("config.json.corrupt").exists());
    }
}
